/**
 * Writes KNOWLEDGE_REVIEW.md: every draft knowledge base entry (not shown on the
 * site) with the exact question the owner must answer before it can be approved.
 *   npm run knowledge:review
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { KNOWLEDGE_BASE } from '@/data/knowledge';
import { KNOWLEDGE_TOPICS } from '@/data/knowledge/types';

const drafts = KNOWLEDGE_BASE.filter((e) => e.status === 'draft');
const approved = KNOWLEDGE_BASE.length - drafts.length;

const lines = [
  '# Knowledge base — entries waiting for your answer',
  '',
  `The website assistant answers from \`src/data/knowledge/\`. ${approved} entries are approved and live; the ${drafts.length} below are **drafts** and are not shown to visitors, because they need a fact that isn't on the website yet.`,
  '',
  'For each one, reply with the answer to the question in bold. The entry is then completed with your facts (in all 4 languages) and switched to `approved`.',
  '',
  '_Generated by `npm run knowledge:review`._',
  '',
];

for (const topic of KNOWLEDGE_TOPICS) {
  const list = drafts.filter((e) => e.topic === topic);
  if (!list.length) continue;
  lines.push(`## ${topic}`, '');
  for (const e of list) {
    lines.push(`### \`${e.id}\` — ${e.question.en}`, '');
    lines.push(`- **Your answer needed:** ${e.review ?? '(no review question)'}`);
    lines.push(`- Hebrew question: ${e.question.he}`);
    lines.push(`- Proposed answer (en): ${e.answer.en.replace(/\s+/g, ' ')}`);
    lines.push(`- File: \`src/data/knowledge/${topic}.ts\``, '');
  }
}

writeFileSync(join(process.cwd(), 'KNOWLEDGE_REVIEW.md'), lines.join('\n'));
console.log(`KNOWLEDGE_REVIEW.md: ${drafts.length} drafts (${approved} approved entries)`);
